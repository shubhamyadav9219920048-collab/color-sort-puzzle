export function getArticlesByCategory(categoryOrSlug: string): BlogArticle[] {
  const norm = categoryOrSlug.toLowerCase().trim();
  return BLOG_ARTICLES.filter(
    (a) =>
      a.category.toLowerCase() === norm ||
      a.categorySlug.toLowerCase() === norm ||
      a.category.toLowerCase().replace(/\s+/g, '-') === norm
  );
}

export function getPopularArticles(limit: number = 6): BlogArticle[] {
  return [...BLOG_ARTICLES]
    .sort((a, b) => (b.views || 0) - (a.views || 0))
    .slice(0, limit);
}

export function getRecentArticles(limit: number = 6): BlogArticle[] {
  return [...BLOG_ARTICLES]
    .sort((a, b) => new Date(b.publishedDate).getTime() - new Date(a.publishedDate).getTime())
    .slice(0, limit);
}

export function getRelatedArticles(currentArticle: BlogArticle, limit: number = 3): BlogArticle[] {
  if (currentArticle.relatedSlugs && currentArticle.relatedSlugs.length > 0) {
    const matched = BLOG_ARTICLES.filter((a) =>
      currentArticle.relatedSlugs?.includes(a.slug)
    );
    if (matched.length >= limit) return matched.slice(0, limit);
  }

  // Fallback to same category or shared tags
  const sameCategory = BLOG_ARTICLES.filter(
    (a) => a.id !== currentArticle.id && a.categorySlug === currentArticle.categorySlug
  );

  if (sameCategory.length >= limit) {
    return sameCategory.slice(0, limit);
  }

  // General fallback
  const remaining = BLOG_ARTICLES.filter(
    (a) => a.id !== currentArticle.id && !sameCategory.some((sc) => sc.id === a.id)
  );

  return [...sameCategory, ...remaining].slice(0, limit);
}

export function searchArticles(query: string): BlogArticle[] {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return BLOG_ARTICLES.filter(
    (a) =>
      a.title.toLowerCase().includes(q) ||
      a.subtitle.toLowerCase().includes(q) ||
      a.summary.toLowerCase().includes(q) ||
      a.category.toLowerCase().includes(q) ||
      a.tags.some((t) => t.toLowerCase().includes(q)) ||
      a.content.toLowerCase().includes(q)
  );
}

